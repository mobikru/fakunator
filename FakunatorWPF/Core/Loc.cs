namespace Fakunator.Core;

/// <summary>
/// Лёгкая локализация без .resx/сателлитных сборок — строки живут прямо в коде
/// (словарь ru/en), а не в отдельных файлах, чтобы не повторить баг с deps.zip,
/// когда вложенные Assets-файлы молча терялись при паковке релиза.
/// Индексатор + PropertyChanged("Item[]") — стандартный WPF-трюк: биндинг вида
/// Path=[key] к Loc.Instance переоценивается сам, когда индексатор "меняется".
/// </summary>
public class Loc : INotifyPropertyChanged
{
    public static Loc Instance { get; } = new Loc();

    public event PropertyChangedEventHandler? PropertyChanged;
    public event System.EventHandler? LanguageChanged;

    private string _lang = Config.Current.Language is "ru" or "en" ? Config.Current.Language : "ru";

    public string Language
    {
        get => _lang;
        set
        {
            if (_lang == value || (value != "ru" && value != "en")) return;
            _lang = value;
            Config.Current.Language = value;
            Config.Current.Save();
            PropertyChanged?.Invoke(this, new PropertyChangedEventArgs("Item[]"));

            // Раздельный try/catch на каждый подписчик: LanguageChanged слушают ~15 разных
            // ViewModel/View по всем разделам. Обычный Invoke() — это цепочка вызовов, и если
            // ХОТЬ ОДИН обработчик кинет необработанное исключение, все следующие в списке
            // просто не выполнятся (вплоть до алфавитного конца подписки) — снаружи это
            // выглядит как "смена языка что-то сломала в совершенно другом разделе".
            foreach (var handler in LanguageChanged?.GetInvocationList() ?? System.Array.Empty<System.Delegate>())
            {
                try { ((System.EventHandler)handler).Invoke(this, System.EventArgs.Empty); }
                catch { /* один сломанный подписчик не должен ронять остальных */ }
            }
        }
    }

    public string this[string key] => T(key);

    public static string T(string key) => Instance.Get(key);

    public string Get(string key)
    {
        if (_tables.TryGetValue(_lang, out var dict) && dict.TryGetValue(key, out var v))
            return v;
        if (_tables.TryGetValue("ru", out var ru) && ru.TryGetValue(key, out var rv))
            return rv;
        return key;
    }

